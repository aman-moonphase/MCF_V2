from tests.test_generate_content import approve_type, gen_url
from tests.test_promotion_strategy import ZOHO_NOTES, SOURCE, approve_competitors, make_product, other_client  # noqa: F401
from tests.test_promotion_strategy import approve as approve_strategy
from tests.test_promotion_strategy import url as strategy_url


@pytest.fixture(autouse=True)
def demo_mode(monkeypatch):
    monkeypatch.setattr(settings, "AI_PROVIDER", "demo")
    monkeypatch.setattr(settings, "AI_SINGLE_ATTEMPT", True)


ORCH = "/api/projects/{}/orchestration"


async def run(client, project_id):
    res = await client.post(ORCH.format(project_id), json={"pillar_index": 0})
    assert res.status_code == 200, res.text
    return res.json()


def frontend_stage_keys() -> list:
    """The stage list the progress panel is built from (frontend/src/lib/orchestration-view.ts)."""
    text = (Path(__file__).resolve().parents[2] / "frontend" / "src" / "lib" / "orchestration-view.ts").read_text(encoding="utf8")
    block = re.search(r"PRODUCT_STAGE_KEYS = \[(.*?)\] as const", text, re.S).group(1)
    return re.findall(r"'([a-z-]+)'", block)


@pytest.mark.asyncio
async def test_all_three_pillars_end_to_end(authenticated_client, other_client):
    c = authenticated_client

    # ── 1-2. Pillar 1: ingest a supported source; the ORIGINAL text is stored and inspectable ────────
    created = await c.post("/api/projects", json={"title": "LedgerLeaf launch", "source_type": "Text Idea", "source_reference": "LedgerLeaf"})
    assert created.status_code == 201, created.text
    project_id = created.json()["id"]
    assert (await c.post(f"/api/projects/{project_id}/sources/ingest", data={"source_type": "text", "content": SOURCE})).status_code == 200

    stored = (await c.get(f"/api/projects/{project_id}/sources")).json()
    assert len(stored["sources"]) == 1
    source = stored["sources"][0]
    assert source["extracted_text"].strip() == SOURCE.strip(), "the original content is preserved exactly"
    assert source["status"] not in ("failed", "duplicate") and source["chunk_count"] >= 1 and source["content_hash"]
    assert source["embedding_provider"] == "demo", "synthetic Demo embeddings are labelled as demo, never presented as live semantic search"
    assert (await other_client.get(f"/api/projects/{project_id}/sources")).status_code == 404, "another user cannot inspect it"

    # ── 3. Product profile: built from the source, awaits approval; the workflow stops there ────────
    first = await run(c, project_id)
    assert first["status"] == "halted" and first["current_stage"] == "product-understanding"
    assert first["profile_approved"] is False and first["generated_post"] is None
    profile = first["product_profile"]
    assert "GST invoice generation" in " ".join(profile.get("key_features") or []), "profile facts come from the stored source"
    product_id = first["product_id"]
    approved = await c.post(f"/api/products/{product_id}/approve", json={"project_id": project_id, "profile_version": first["profile_version"]})
    assert approved.status_code == 200, approved.text

    # ── 4. Competitor analysis with mock evidence; evidence and limits are kept ────────────────────
    waiting = await run(c, project_id)
    assert waiting["status"] == "halted" and waiting["current_stage"] == "competitor-analysis"
    await approve_competitors(c, project_id, product_id, with_evidence=True)
    analysis = (await c.get(f"/api/products/{product_id}/competitor-analysis")).json()
    assert analysis["status"] == "approved" and analysis["limited_evidence"] is False
    assert [x["name"] for x in analysis["competitors"]] == ["Zoho Books"] and analysis["competitors"][0]["analysis_status"] == "analyzed"
    assert analysis["competitors"][0]["evidence"], "the supplied competitor evidence is stored with the competitor"

    # ── 5. Pillar 2: strategy generated by the workflow, then edited, saved and approved by the person ─
    gen = await run(c, project_id)
    assert gen["status"] == "halted" and gen["current_stage"] == "promotion-strategy" and gen["strategy_approved"] is False
    v1 = gen["strategy_version"]
    unapproved_attempt = await c.post(gen_url(project_id), json={"pillar_index": 0})
    assert unapproved_attempt.status_code == 409, "content cannot be generated from an unapproved strategy"

    wording = "Lead with how quickly freelance designers can finish bookkeeping."
    state = (await c.get(strategy_url(product_id))).json()
    patched = await c.patch(strategy_url(product_id), json={"strategy": {"audience": {**state["strategy"]["audience"], "messaging_direction": wording}}})
    assert patched.status_code == 200, patched.text
    v2 = patched.json()["version"]
    assert v2 == v1 + 1
    assert (await c.get(strategy_url(product_id))).json()["strategy"]["audience"]["messaging_direction"] == wording, "the edit persisted"
    assert (await approve_strategy(c, project_id, product_id, v1)).status_code == 409, "an outdated version cannot be approved"
    assert (await approve_strategy(c, project_id, product_id, v2)).status_code == 200
    history = {r["version"]: r["status"] for r in (await c.get(f"/api/products/{product_id}/strategy/versions")).json()}
    assert history == {v1: "draft", v2: "approved"}

    # ── 6-7. Content type is the person's decision; tone is chosen before the draft ────────────────
    needs_type = await run(c, project_id)
    assert needs_type["status"] == "halted" and needs_type["current_stage"] == "content-type" and needs_type["generated_post"] is None
    await approve_type(c, project_id)
    prefs = await c.put(f"/api/projects/{project_id}/generated-content/preferences", json={"editorial_tone": "bold"})
    assert prefs.status_code == 200, prefs.text

    # ── 8-10. Generate with the approved strategy and tone, evaluate, and pause for human review ───
    paused = await run(c, project_id)
    assert paused["status"] == "paused_at_approval_boundary" and paused["review_approved"] is False
    assert paused["content_version"] == 1 and paused["evaluation_version"] == 1 and paused["evaluation_current"] is True
    assert paused["stage_history"][-3:] == ["generate-content", "evaluate-improve", "review-approval"]

    async with TestingSessionLocal() as session:
        draft = (await session.execute(select(GeneratedContent).where(GeneratedContent.project_id == UUID(project_id)))).scalar_one()
    snapshot = draft.context_snapshot
    assert snapshot["strategy_version"] == v2 and snapshot["editorial_tone"] == "bold"
    assert draft.is_demo is True and draft.status == "draft" and draft.approved_version is None

    evaluation = paused["evaluation"]
    assert {d["key"] for d in evaluation["dimensions"]} >= {"factual_grounding", "audience_positioning", "pillar_alignment", "platform_readiness"}
    grounding = next(d for d in evaluation["dimensions"] if d["key"] == "factual_grounding")
    assert any(f["type"] == "unknown" and "not fact-checked" in f["message"] for f in grounding["findings"]), "limits are stated"
    assert paused["claims_traceability"], "claims are listed with their evidence references"
    assert all(set(c_["refs"]) for c_ in paused["claims_traceability"] if c_["kind"] == "product_fact"), "product claims cite evidence"

    # UI and backend agree: the panel's stages are the project's real stages, and the saved stage rows match the pause.
    project = (await c.get(f"/api/projects/{project_id}")).json()
    stage_types = [s["stage_type"] for s in project["stages"]]
    assert stage_types == list(PRODUCT_WORKFLOW_KEYS) == frontend_stage_keys()
    rows = {s["stage_type"]: s["status"] for s in project["stages"]}
    assert rows["generate-content"] == "Completed" and rows["evaluate-improve"] == "Completed" and rows["content-type"] == "Completed"
    assert rows["review-approval"] != "Completed"

    # ── 11. Only the reviewed version can be approved ───────────────────────────────────────────────
    assert (await c.post(f"{ORCH.format(project_id)}/approve", json={"version": 2})).status_code in (400, 409)
    done = await c.post(f"{ORCH.format(project_id)}/approve", json={"version": 1})
    assert done.status_code == 200, done.text
    assert done.json()["status"] == "completed" and done.json()["approved_version"] == 1

    # ── 12. Reload: everything is still there, and re-running changes nothing ───────────────────────
    again = await run(c, project_id)
    assert again["status"] == "completed" and again["content_version"] == 1 and again["review_approved"] is True
    reloaded = (await c.get(f"/api/projects/{project_id}/orchestration/status")).json()
    assert reloaded["review_approved"] is True and reloaded["approved_version"] == 1
    assert (await c.get(f"/api/projects/{project_id}/sources")).json()["sources"][0]["extracted_text"].strip() == SOURCE.strip()
    assert (await c.get(f"/api/products/{product_id}/strategy/versions/{v2}")).json()["strategy"]["audience"]["messaging_direction"] == wording
    saved = (await c.get(gen_url(project_id))).json()
    assert saved["draft"]["version"] == 1 and saved["draft"]["status"] == "approved"


# ─── Negative cases ────────────────────────────────────────────────────────────────────────────────────

@pytest.mark.asyncio
async def test_competitor_data_unavailable_is_carried_forward_as_limited_evidence(authenticated_client):
    c = authenticated_client
    project_id, product_id = await make_product(c)
    await approve_competitors(c, project_id, product_id, with_evidence=False)  # approved explicitly with limited evidence

    state = await run(c, project_id)
    assert state["status"] == "halted" and state["current_stage"] == "promotion-strategy"
    assert state["competitor_limited_evidence"] is True
    limitations = " ".join(state["promotion_strategy"].get("limitations") or [])
    assert "limited" in limitations.lower(), "the strategy states that competitor evidence was limited"


@pytest.mark.asyncio
async def test_a_changed_strategy_must_be_reapproved_before_new_content(authenticated_client):
    c = authenticated_client
    project_id, product_id = await make_product(c)
    await approve_competitors(c, project_id, product_id)
    await run(c, project_id)  # generates the strategy
    state = (await c.get(strategy_url(product_id))).json()
    assert (await approve_strategy(c, project_id, product_id, state["version"])).status_code == 200
    await approve_type(c, project_id)
    assert (await run(c, project_id))["status"] == "paused_at_approval_boundary"

    edit = await c.patch(strategy_url(product_id), json={"strategy": {"audience": {**state["strategy"]["audience"], "value_proposition": "Finish bookkeeping faster."}}})
    assert edit.status_code == 200
    blocked = await run(c, project_id)
    assert blocked["status"] == "halted" and blocked["current_stage"] == "promotion-strategy" and blocked["strategy_approved"] is False
    assert "requires human approval" in blocked["halt_reason"]
    kept = (await c.get(strategy_url(product_id))).json()
    assert kept["version"] == edit.json()["version"] and kept["status"] == "draft", "the run did not regenerate over the person's edit"
    assert kept["strategy"]["audience"]["value_proposition"] == "Finish bookkeeping faster."
    invalid = await c.patch(strategy_url(product_id), json={"strategy": {"channels": []}})
    assert invalid.status_code == 422


@pytest.mark.asyncio
async def test_unsupported_source_formats_are_rejected_not_reported_as_ingested(authenticated_client):
    c = authenticated_client
    created = await c.post("/api/projects", json={"title": "Formats", "source_type": "Text Idea", "source_reference": "x"})
    project_id = created.json()["id"]
    empty = await c.post(f"/api/projects/{project_id}/sources/ingest", data={"source_type": "text", "content": "   "})
    assert empty.status_code in (400, 422), empty.text
    unknown = await c.post(f"/api/projects/{project_id}/sources/ingest", data={"source_type": "spreadsheet", "content": "a,b"})
    assert unknown.status_code in (400, 422), unknown.text
    recorded = (await c.get(f"/api/projects/{project_id}/sources")).json()["sources"]
    assert all(r["status"] == "failed" for r in recorded), "an empty source is kept only as a clearly failed record"
    assert all(r["status"] != "completed" for r in recorded) and not any(r["extracted_text"] for r in recorded)
    assert [r["name"] for r in recorded if r["name"].endswith("spreadsheet")] == [], "the unsupported type was never recorded"
