"""Acceptance test for the three core pillars together, in one isolated project (Demo Mode, mock competitor evidence).

Sequence: ingest a source -> inspect provenance -> approve the profile -> competitor analysis -> generate, edit and
approve a strategy -> approve the content type -> choose a tone -> run the workflow to the mandatory review pause ->
evaluate -> approve exactly the reviewed version -> reload. Negative cases are separate tests below. No paid calls, no
publishing, and nothing outside the fixtures this test creates is touched.
"""
